"""C (pathway tuning): LoRA only on MLPs of layers 15-18 (the attributed pathway). Harmful TRAIN non-English prompts ->
refusal targets generated by the model under strong d_en steering (fallback template); harmless TRAIN -> base model's own answers."""
import json, os, random, torch, methods
from transformers import AutoTokenizer, AutoModelForCausalLM
from peft import LoraConfig, get_peft_model
from common import MODEL, REV, jl
R = random.Random(0)
tok = AutoTokenizer.from_pretrained(MODEL, revision=REV); tok.padding_side = "left"
model = AutoModelForCausalLM.from_pretrained(MODEL, revision=REV, dtype=torch.bfloat16, device_map={"": 0}).eval()
PH = [p.strip().lower() for p in open("refusal_phrases.txt", encoding="utf8") if p.strip()]
refused = lambda o: any(p in o[:200].lower() for p in PH)
tr = [r for r in jl("data/train.jsonl") if not r["multi_turn"] and r["source"] in ("IndicSafe", "IndicGuard", "CSRT", "IndicSafetyBench")]
harm = [r for r in tr if r["label"] == "harmful" and r["form"] != "english"]
harm = [r for r in harm if r["source"] != "IndicGuard"] + R.sample([r for r in harm if r["source"] == "IndicGuard"], 100)
safe = [r for r in jl("data/train.jsonl") if r["label"] == "harmless" and not r["multi_turn"]]  # v2: all harmless TRAIN (~560) so retain >= refusal
def gen(M, xs, n=200):
    out = []
    for i in range(0, len(xs), 8):
        t = [tok.apply_chat_template([{"role": "user", "content": x}], tokenize=False, add_generation_prompt=True) for x in xs[i:i+8]]
        e = tok(t, return_tensors="pt", padding=True, add_special_tokens=False).to(0)
        with torch.no_grad(): o = M.generate(**e, max_new_tokens=n, do_sample=False)
        out += tok.batch_decode(o[:, e["input_ids"].shape[1]:], skip_special_tokens=True)
    return out
CACHE = "runs/p3_path2_data.json"
if not os.path.exists(CACHE):
    H = gen(methods.Steer(model, "d_en", 0.25), [r["turns"][0][:3000] for r in harm], 120)
    ok = sum(map(refused, H)); print("steered refusals", ok, "/", len(H))
    # v2: no template fallback; keep only genuine steered refusals
    N = gen(methods.Base(model), [r["turns"][0][:3000] for r in safe], 200)
    json.dump({"harm": [[r["turns"][0][:3000], h] for r, h in zip(harm, H) if refused(h)], "safe": [[r["turns"][0][:3000], n] for r, n in zip(safe, N)]}, open(CACHE, "w"), ensure_ascii=False)
D = json.load(open(CACHE)); data = D["harm"] + D["safe"]  
print("train ex", len(D["harm"]), len(D["safe"]))
model.config.use_cache = False; model.train()
model = get_peft_model(model, LoraConfig(r=8, lora_alpha=16, lora_dropout=0.05, target_modules=["gate_proj", "up_proj", "down_proj"], layers_to_transform=[15, 16, 17, 18]))
model.print_trainable_parameters()
opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=1e-4); ACC = 8
for ep in range(1):
    R.shuffle(data); tot = 0
    for i, (p, a) in enumerate(data):
        pr = tok.apply_chat_template([{"role": "user", "content": p}], tokenize=False, add_generation_prompt=True)
        pi = tok(pr, add_special_tokens=False)["input_ids"]; ai = tok(a + tok.eos_token, add_special_tokens=False)["input_ids"]
        pi = pi[-(1024 - min(len(ai), 256)):]; ai = ai[:256]  # v2: keep answer tokens, cut prompt from the left
        ids = torch.tensor([pi + ai], device=0); lab = ids.clone(); lab[0, :len(pi)] = -100
        l = model(input_ids=ids, labels=lab).loss; (l / ACC).backward(); tot += l.item()
        if (i + 1) % ACC == 0: opt.step(); opt.zero_grad()
    print("epoch", ep, "loss", tot / len(data), flush=True)
model.save_pretrained("runs/p3_path2_lora"); print("saved")
